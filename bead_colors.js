function findClosestBeadColor(hex) {
  const m = hex.match(/\d+/g);
  if (!m) return null;
  const r = +m[0], g = +m[1], b = +m[2];
  let minDist = Infinity, best = null;
  for (const [bh, code, name] of BEAD_COLORS) {
    const bm = bh.match(/[0-9a-f]{2}/gi);
    const br = parseInt(bm[0],16), bg = parseInt(bm[1],16), bb = parseInt(bm[2],16);
    const dist = (r-br)**2 + (g-bg)**2 + (b-bb)**2;
    if (dist < minDist) { minDist = dist; best = {hex:bh, code, name, dist}; }
  }
  return best;
}
